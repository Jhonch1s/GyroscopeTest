-- Tabla: perfil
CREATE TABLE perfil (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  nombre text NOT NULL,
  email text,
  contrasena text,
  f_nac date,
  imagen_perfil text,
  creado_en timestamptz DEFAULT now()
);

-- Tabla: mision
CREATE TABLE mision (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tipo tipo_mision NOT NULL,
  nombre text NOT NULL,
  descripcion text,
  recompensa categoria_carta NOT NULL
);

-- Tabla: carta
CREATE TABLE carta (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  nombre_carta text,
  categoria categoria_carta NOT NULL,
  borde text,
  imagen text,
  centro text,
  normal_map text,
  texto varchar(255),
  propietario int REFERENCES perfil(id) ON DELETE SET NULL,
  creada_en timestamptz DEFAULT now()
);

-- Tabla: texto_educativo
CREATE TABLE texto_educativo (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  contenido text NOT NULL
);

-- Tabla: trivia_utec
CREATE TABLE trivia_utec (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  pregunta text NOT NULL,
  opcion1 text NOT NULL,
  opcion2 text NOT NULL,
  opcion3 text NOT NULL,
  opcion4 text NOT NULL,
  respuesta_correcta int NOT NULL CHECK (respuesta_correcta BETWEEN 1 AND 4)
);

-- Tabla: progreso_usuario
CREATE TABLE progreso_usuario (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  perfil_id int REFERENCES perfil(id) ON DELETE CASCADE,
  mision_id int REFERENCES mision(id) ON DELETE CASCADE,
  completado boolean DEFAULT false,
  fallado boolean DEFAULT false,
  fecha date DEFAULT current_date
);

