-- 5. FUNCIONES
-----------------------------------------
CREATE OR REPLACE FUNCTION get_daily_missions(p_perfil_id int, limit_count int DEFAULT 3)
RETURNS SETOF mision AS $$
DECLARE
    v_conteo int;
BEGIN
    -- 1. Contar cuántas misiones tiene asignadas el usuario HOY
    SELECT COUNT(*) INTO v_conteo 
    FROM progreso_usuario 
    WHERE perfil_id = p_perfil_id AND fecha = CURRENT_DATE;

    -- 2. Si no tiene misiones asignadas hoy, elegimos 3 al azar y las congelamos
    IF v_conteo = 0 THEN
        INSERT INTO progreso_usuario (perfil_id, mision_id, completado, fallado, fecha)
        SELECT p_perfil_id, id, false, false, CURRENT_DATE
        FROM mision
        ORDER BY random()
        LIMIT limit_count;
    END IF;

    -- 3. Devolver las misiones que quedaron asociadas al usuario para el día de hoy
    RETURN QUERY 
    SELECT m.* FROM mision m
    JOIN progreso_usuario p ON p.mision_id = m.id
    WHERE p.perfil_id = p_perfil_id AND p.fecha = CURRENT_DATE AND p.completado = FALSE AND p.fallado = FALSE;
END;
$$ LANGUAGE plpgsql;

